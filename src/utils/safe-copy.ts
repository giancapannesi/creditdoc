export function softenYmylCopy(text: string): string {
  return text
    .replace(/money-back guarantees/gi, 'listed refund terms')
    .replace(/money-back guarantee/gi, 'listed refund term')
    .replace(/service guarantee/gi, 'service term')
    .replace(/guarantees before engaging/gi, 'terms before contacting the provider')
    .replace(/\bguarantees\b/gi, 'stated terms')
    .replace(/effective credit repair/gi, 'credit repair services')
    .replace(/without overpaying/gi, 'with listed pricing context')
    .replace(/zero upfront cost to get started/gi, 'no listed setup fee')
    .replace(/comparable effectiveness/gi, 'comparable profile fields')
    .replace(/\bthe better value\b/gi, 'the lower listed-cost comparison')
    .replace(/\bbest value\b/gi, 'lower listed-cost profile')
    .replace(/\bsuperior value\b/gi, 'stronger listed-cost context')
    .replace(/\bstronger value\b/gi, 'stronger listed-cost context')
    .replace(/\bsafer choice\b/gi, 'lower-risk profile to compare')
    .replace(/\bclear choice\b/gi, 'clearer profile to compare')
    .replace(/\bthe better choice\b/gi, 'the clearer profile to compare')
    .replace(/\bthe best choice\b/gi, 'the profile to compare')
    .replace(/\bbest choice\b/gi, 'profile to compare')
    .replace(/\bbest option\b/gi, 'option to compare')
    .replace(/\bright choice\b/gi, 'option to compare')
    .replace(/\btop companies compared\b/gi, 'company profiles compared')
    .replace(/\bfull rankings & reviews\b/gi, 'provider profiles and comparisons')
    .replace(/\bCompare the Best\b/gi, 'Compare')
    .replace(/\bbest for\b/gi, 'profile signals for')
    .replace(/\bBest For\b/g, 'Profile Signals')
    .replace(/\btop lenders\b/gi, 'listed lenders')
    .replace(/\btop personal loan lenders\b/gi, 'personal loan lender profiles')
    .replace(/\btop secured cards\b/gi, 'secured card profiles')
    .replace(/\bSee Top 5\b/gi, 'See')
    .replace(/\bget matched with lenders\b/gi, 'review lender options')
    .replace(/\bget matched\b/gi, 'review options')
    .replace(/\bactually approve borrowers\b/gi, 'publish eligibility fields')
    .replace(/\bapproval odds\b/gi, 'eligibility fields')
    .replace(/\bwins\b/gi, 'is flagged')
    .replace(/Our editorial team independently evaluates all services\. Compensation does not influence editorial reviews, page order, or recommendations;/gi, 'Compensation does not determine whether a provider can be covered or how visible star ratings are calculated;')
    .replace(/Compensation does not influence editorial reviews, page order, or recommendations;/gi, 'Compensation does not determine whether a provider can be covered or how visible star ratings are calculated;');
}
